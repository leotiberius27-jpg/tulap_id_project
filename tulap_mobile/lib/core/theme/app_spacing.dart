/// AppSpacing
/// ----------------------------------------------------------------------
/// Token spacing berbasis skala 8px, sesuai Bagian 22 dokumen spesifikasi.
/// Padding horizontal default layar mobile adalah [screenPadding] (16px).
/// ----------------------------------------------------------------------
class AppSpacing {
  AppSpacing._();

  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double base = 16;
  static const double lg = 24;
  static const double xl = 32;
  static const double xxl = 40;
  static const double xxxl = 48;
  static const double huge = 64;

  /// Padding horizontal standar untuk seluruh layar mobile Tulap.id
  static const double screenPadding = base;
}
